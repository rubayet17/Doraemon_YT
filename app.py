import streamlit as st
from supabase import create_client, Client
from llm_engine import call_master_brain  # Importing LLM Fallback Engine

# Page Config
st.set_page_config(page_title="Doraemon MAS Control Hub", page_icon="🤖", layout="wide")

# Secrets Retrieval & Initialization
try:
    SUPABASE_URL = st.secrets["SUPABASE_URL"]
    SUPABASE_KEY = st.secrets["SUPABASE_KEY"]
    supabase: Client = create_client(SUPABASE_URL, SUPABASE_KEY)
    db_connected = True
except Exception as e:
    db_connected = False
    st.sidebar.error(f"❌ Supabase Connection Error: {e}")

# Core Mission Header
st.markdown("### 🎯 Core Mission Metric: **Watch Time + Viewer Satisfaction 100% Guaranteed** (Zero Clickbait)")
st.write("---")

# Dynamic Channel Fetching
channel_list = ["Default Channel"]
channel_dict = {}

if db_connected:
    try:
        res = supabase.table("channels").select("id, channel_name").execute()
        if res.data:
            channel_list = [ch["channel_name"] for ch in res.data]
            channel_dict = {ch["channel_name"]: ch["id"] for ch in res.data}
    except Exception:
        pass

# Sidebar Channel Selector (Sub-room Switcher)
st.sidebar.title("🤖 Doraemon MAS Engine")
selected_channel = st.sidebar.selectbox("📁 Select Channel Sub-Room", channel_list)
current_channel_id = channel_dict.get(selected_channel, "general_room")

if db_connected:
    st.sidebar.success(f"✅ Connected to Sub-Room: {selected_channel}")
else:
    st.sidebar.warning("⚠️ Running in Offline UI Mode")

# Visual Tabs
tab1, tab2, tab3, tab4 = st.tabs([
    "📊 Channels Overview", 
    "📜 Scripts & Content Pipeline", 
    "🎬 1-Click Approval Gate", 
    f"💬 Visual Doraemon [{selected_channel}]"
])

with tab1:
    st.subheader(f"Performance Metrics for: {selected_channel}")
    try:
        res = supabase.table("channels").select("*").execute()
        st.dataframe(res.data, use_container_width=True)
    except Exception:
        st.info("Channels table loading or waiting for initial data...")

with tab2:
    st.subheader(f"Content & Retention Pipeline ({selected_channel})")
    try:
        res = supabase.table("scripts_and_videos").select("*").execute()
        st.dataframe(res.data, use_container_width=True)
    except Exception:
        st.info("Scripts and videos database sync pending...")

with tab3:
    st.subheader("Human-in-the-Loop Approval Gate")
    st.success("Videos generated by Kaggle GPU will pause here for Rini's final review before publishing to YouTube!")

with tab4:
    st.subheader(f"🧠 Master Doraemon Brain - Sub-Room: {selected_channel}")
    st.write(f"Isolated sub-room active. Conversations stay strictly within **{selected_channel}** context.")
    
    # Initialize Channel-Isolated Chat History
    if "chat_histories" not in st.session_state:
        st.session_state.chat_histories = {}
    
    if current_channel_id not in st.session_state.chat_histories:
        st.session_state.chat_histories[current_channel_id] = [
            {"role": "assistant", "content": f"Namaskar Rini! Ami Doraemon. Apni ekhon **{selected_channel}** sub-room-e achen."}
        ]

    for message in st.session_state.chat_histories[current_channel_id]:
        with st.chat_message(message["role"]):
            st.markdown(message["content"])

    if user_prompt := st.chat_input(f"Command Doraemon for {selected_channel}..."):
        st.session_state.chat_histories[current_channel_id].append({"role": "user", "content": user_prompt})
        with st.chat_message("user"):
            st.markdown(user_prompt)

        system_instruction = f"""
        You are Doraemon, Master Multi-Agent Orchestrator for Rini's YouTube system.
        Active channel sub-room: {selected_channel} (ID: {current_channel_id}).
        Strict Core Metric: 1. Maximize Watch Time, 2. Viewer Satisfaction. Zero clickbait.
        """

        with st.chat_message("assistant"):
            with st.spinner("Doraemon processing fallback LLM routing..."):
                reply_text, active_llm = call_master_brain(user_prompt, system_instruction)
                bot_reply = f"{reply_text}\n\n*— Powered by: {active_llm}*"
                
                st.markdown(bot_reply)
                st.session_state.chat_histories[current_channel_id].append({"role": "assistant", "content": bot_reply})
